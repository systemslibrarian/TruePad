/* ============================================================================
 * TruePad Browser Edition — the randomness SOURCE claim, worded once
 * ----------------------------------------------------------------------------
 * The governing rule of the whole project applies hardest here:
 *
 *   The XOR is already a true one-time pad. The machinery only keeps the
 *   theorem's hypotheses true OUTSIDE the equation. Never promote an
 *   engineering action into a stronger cryptographic claim than it deserves.
 *
 * So the COMBINER and the SOURCE are graded separately, and this module keeps
 * the two apart in the only place a user reads them — the words.
 *
 *   COMBINER (both paths, unconditional): every declared source supplies the
 *   complete L = 2·(E + 32·N) bytes; they are XORed byte-for-byte; the result
 *   is partitioned into the four secret slices. No KDF, no extractor, no hash
 *   conditioner, no whitening, no statistical gate, no content-dependent
 *   rejection. This is exact, and it is the same on both paths.
 *
 *   SOURCE (graded, and NOT the same on the two paths):
 *     · Device-generated — crypto.getRandomValues(). A cryptographically
 *       secure platform generator. COMPUTATIONAL: its security rests on
 *       platform and computational assumptions. Never called physically
 *       proven, verified, or information-theoretic.
 *     · External ceremony — operator-supplied material. ELIGIBLE for the
 *       information-theoretic premise, and only eligible: the premise is true
 *       if and only if the operator's physical assumptions are actually true,
 *       which no software can determine. The claim therefore stays
 *       conditional, in every sentence, forever.
 *
 * The operator declaration below is an OPERATOR DECLARATION and never a
 * verification result. Nothing here may ever read "verified", "certified",
 * "passed", "confirmed", or "proven".
 *
 * The verdict itself is NOT restated here on purpose: it is the engine's
 * string, shown back verbatim from the gen reply, so the UI can never drift
 * from what the combiner actually claims.
 * ========================================================================= */

