export function ceremonyLengthRule(required: number): string {
  return (
    `Every source must independently supply the full ${required.toLocaleString("en-US")} bytes. Sources are never ` +
    `concatenated and never split between them — each one covers the whole pad — and anything beyond that length ` +
    `is unused.`
  );
}

